    # -- per-twin failure attribution ------------------------------------

    def test_transpile_failure_keeps_its_path_and_diagnostic(self) -> None:
        self.add_twin("models/good_one", "package models", "val goodOne = 1")
        self.add_twin("models/broken", "package models", "val broken = 1", "BROKEN")
        self.add_twin("models/good_two", "package models", "val goodTwo = 2")
        self.add_twin("utils/only", "package utils", "val only = 1")

        result = self.run_verify()
        output = self.output(result)
        self.assertEqual(result.returncode, 1, output)
        self.assertIn("models/good_one.gala ... ok", output)
        self.assertIn("models/broken.gala ... TRANSPILE", output)
        self.assertIn("models/good_two.gala ... ok", output)
        self.assertIn("utils/only.gala ... ok", output)
        self.assertIn("TRANSPILE: models/broken.gala does not transpile", output)
        self.assertIn("GALA-E9999: boom", output)
        self.assertIn("twins: 4 discovered, 3 transpiled, 3 ok, 1 transpile failure", output)
        self.assertIn("verify.sh: FAILED", output)

        shared = self.shared_calls()
        self.assertEqual(len(shared), 2, "both packages still get their shared call")
        models = next(
            call
            for call in shared
            if call.cwd == self.repo / "server" / "models"
        )
        self.assertEqual(
            sorted(models.inputs()), ["broken.gala", "good_one.gala", "good_two.gala"]
        )
        single = self.single_calls()
        self.assertEqual(len(single), 1, "the failed twin alone is retried")
        self.assertEqual(single[0].cwd, self.repo / "server" / "models")
        self.assertEqual(single[0].values["-i"], "broken.gala")

    # -- command-line and log contract -----------------------------------

    def test_cli_and_log_contract(self) -> None:
        self.add_twin("models/alpha", "package models", "val alpha = 1")

        verbose = self.run_verify("--verbose")
        output = self.output(verbose)
        self.assert_ok(verbose)
        self.assertIn("$ (cd server/models && gala transpile-package", output)
        self.assertIn("--scan", output)
        self.assertIn("--stdlib-module go.gala.fyi/stdlib", output)

        (self.repo / "server" / ".gala" / "verify.log").unlink()
        no_log = self.run_verify("--no-log")
        self.assert_ok(no_log)
        self.assertIn("log:  (disabled)", self.output(no_log))
        self.assertFalse(
            (self.repo / "server" / ".gala" / "verify.log").exists(),
            "--no-log must not write the default run log",
        )

        custom_log = self.run_verify("--log", str(self.repo / "custom.log"))
        self.assert_ok(custom_log)
        self.assertIn(f"log:  {self.repo / 'custom.log'}", self.output(custom_log))
        self.assertTrue((self.repo / "custom.log").is_file())

        conflict = self.run_verify("--write", "--check")
        self.assertEqual(conflict.returncode, 2, self.output(conflict))
        conflict = self.run_verify(
            "--log", str(self.repo / "x.log"), "--no-log"
        )
        self.assertEqual(conflict.returncode, 2, self.output(conflict))

        self.assertEqual(self.run_verify("--jobs", "0").returncode, 2)
        self.assertEqual(self.run_verify("--jobs", "two").returncode, 2)
        self.assertEqual(self.run_verify("-j", "-1").returncode, 2)

    # -- bounded concurrency and deterministic reporting -----------------

    def test_package_groups_run_concurrently_within_the_bound(self) -> None:
        for name in ("alpha", "beta", "gamma", "delta"):
            self.add_twin(
                f"pkg_{name}/main", f"package pkg_{name}", f'val v = "{name}"'
            )

        serial = self.run_verify("--jobs", "1", env={"STUB_SLEEP": "0.5"})
        self.assert_ok(serial)
        self.assertEqual(
            self.peak_concurrency("gala", "transpile-package"),
            1,
            "a single worker must not overlap package groups",
        )

        bounded = self.run_verify("--jobs", "2", env={"STUB_SLEEP": "0.5"})
        self.assert_ok(bounded)
        self.assertEqual(len(self.shared_calls()), 4)
        peak = self.peak_concurrency("gala", "transpile-package")
        self.assertEqual(
            peak, 2, "independent groups overlap up to the worker bound, not past it"
        )

        wide = self.run_verify("--jobs", "4", env={"STUB_SLEEP": "0.5"})
        self.assert_ok(wide)
        peak = self.peak_concurrency("gala", "transpile-package")
        self.assertGreaterEqual(peak, 2, "four workers must overlap groups")
        self.assertLessEqual(peak, 4)
        self.assertIn("package groups: 4 (4 workers)", self.output(wide))

    def test_report_is_deterministic_across_worker_counts(self) -> None:
        self.add_twin("alpha/one", "package alpha", "val one = 1")
        self.add_twin("alpha/broken", "package alpha", "val broken = 1", "BROKEN")
        self.add_twin("beta/two", "package beta", "val two = 2")
        self.modify_source("beta/two", "val added = 3")
        self.add_twin("gamma/three", "package gamma", "val three = 3")
        self.add_twin(
            "gamma/runtime", "package gamma", 'import "martianoff/gala/std"'
        )
        self.add_twin("omega/four", "package omega", "val four = 4")
        (self.repo / "server" / "omega" / "four.go").unlink()

        # The first group is made the slowest, so under four workers it
        # finishes after the later groups while its report must still come first.
        delays = {"STUB_SLEEP": "0.05", "STUB_DELAY_broken": "0.5"}

        serial = self.run_verify("--jobs", "1", env=delays)
        self.assertEqual(serial.returncode, 1, self.output(serial))
        log_path = self.repo / "server" / ".gala" / "verify.log"
        serial_log = log_path.read_text(encoding="utf-8")

        parallel = self.run_verify("--jobs", "4", env=delays)
        self.assertEqual(parallel.returncode, 1, self.output(parallel))
        parallel_log = log_path.read_text(encoding="utf-8")

        self.assertEqual(
            self.stable_report(self.output(serial)),
            self.stable_report(self.output(parallel)),
            "the report must not depend on the worker count or completion order",
        )

        def strip_stamp(line: str) -> str:
            return re.sub(r"^\d\d:\d\d:\d\d ", "", line)

        self.assertEqual(
            self.stable_report(
                "\n".join(strip_stamp(line) for line in serial_log.splitlines())
            ),
            self.stable_report(
                "\n".join(strip_stamp(line) for line in parallel_log.splitlines())
            ),
            "the run log must be deterministic too",
        )

        lines = self.twin_lines(parallel.stdout)
        indices = [int(re.match(r"\[(\d+)/", line).group(1)) for line in lines]
        self.assertEqual(indices, sorted(indices))
        self.assertEqual(len(lines), 6)

        log_lines = [strip_stamp(line).strip() for line in parallel_log.splitlines()]
        for line in lines + self.problem_lines(parallel.stdout):
            self.assertIn(line, log_lines, "the run log must carry every report line")

        ends = {}
        for call in self.calls():
            if (
                call.tool == "gala"
                and call.phase == "end"
                and call.argv[:1] == ["transpile-package"]
            ):
                ends[call.cwd.relative_to(self.repo).as_posix()] = call.at
        self.assertGreater(
            ends["server/alpha"],
            ends["server/gamma"],
            "the fixture must force the first group to finish last",
        )

