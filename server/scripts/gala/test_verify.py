#!/usr/bin/env python3
"""Fixture tests for the GALA twin verifier, without the real compiler.

Every case builds a small git repository in a temporary directory and puts
stub `gala`, `go`, and `gofmt` executables on `PATH`.  The stub compiler shares
one process per `transpile-package` invocation, writes one output per input,
and fails a single input on demand, so the test can assert:

- one shared invocation per source directory instead of one per twin,
- per-twin drift, missing-output, and banned-runtime reporting,
- a twin that fails to transpile keeps its path and compiler diagnostic while
  the rest of its package and the remaining packages are still verified,
- the command-line and log contract (exit codes, --write, --verbose, --no-log).

The fixture needs only `git` and `bash`; it never runs the real GALA compiler.

Usage:
    python3 server/scripts/gala/test_verify.py
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

VERIFY = Path(__file__).resolve().parent / "verify.py"
GENERATED_HEADER = "// Code generated by GALA transpiler. DO NOT EDIT."

GALA_STUB = r"""#!/usr/bin/env bash
set -u
printf 'gala\t%s\t%s\n' "$PWD" "$*" >>"${STUB_CALL_LOG:-/dev/null}"

emit() {
  local input="$1" output="$2"
  if [ ! -f "$input" ]; then
    printf 'Error reading %s: missing\n' "$input" >&2
    return 1
  fi
  if grep -q BROKEN "$input"; then
    printf 'Error transpiling %s: GALA-E9999: boom\n' "$input" >&2
    return 1
  fi
  mkdir -p "$(dirname "$output")"
  {
    printf '%s\n' '// Code generated by GALA transpiler. DO NOT EDIT.'
    cat "$input"
  } >"$output"
  return 0
}

case "${1:-}" in
  version)
    printf 'GALA version 9.9.9\n'
    ;;
  transpile)
    shift
    input="" output=""
    while [ $# -gt 0 ]; do
      case "$1" in
        -i) input="$2"; shift 2 ;;
        -o) output="$2"; shift 2 ;;
        *) shift ;;
      esac
    done
    emit "$input" "$output"
    ;;
  transpile-package)
    shift
    inputs="" outputs=""
    while [ $# -gt 0 ]; do
      case "$1" in
        --inputs) inputs="$2"; shift 2 ;;
        --outputs) outputs="$2"; shift 2 ;;
        *) shift ;;
      esac
    done
    IFS=',' read -r -a in_arr <<<"$inputs"
    IFS=',' read -r -a out_arr <<<"$outputs"
    if [ "${#in_arr[@]}" -ne "${#out_arr[@]}" ]; then
      printf 'Error: %d inputs != %d outputs\n' "${#in_arr[@]}" "${#out_arr[@]}" >&2
      exit 1
    fi
    failed=0
    for i in "${!in_arr[@]}"; do
      if ! emit "${in_arr[$i]}" "${out_arr[$i]}"; then
        failed=1
      fi
    done
    exit "$failed"
    ;;
  *)
    printf 'unexpected gala invocation: %s\n' "$*" >&2
    exit 2
    ;;
esac
"""

GO_STUB = r"""#!/usr/bin/env bash
set -u
printf 'go\t%s\t%s\n' "$PWD" "$*" >>"${STUB_CALL_LOG:-/dev/null}"
case "${1:-}" in
  version) printf 'go version go9.9 linux/amd64\n' ;;
  build) exit 0 ;;
  *) exit 2 ;;
esac
"""

GOFMT_STUB = r"""#!/usr/bin/env bash
set -u
printf 'gofmt\t%s\t%s\n' "$PWD" "$*" >>"${STUB_CALL_LOG:-/dev/null}"
exit 0
"""


class Invocation:
    """One logged stub invocation: its working directory and parsed options."""

    def __init__(self, cwd: Path, argv: list[str]) -> None:
        self.cwd = cwd
        self.argv = argv
        self.flags: set[str] = set()
        self.values: dict[str, str] = {}
        index = 0
        while index < len(argv):
            token = argv[index]
            if token in {"-i", "-o"}:
                if index + 1 < len(argv):
                    self.values[token] = argv[index + 1]
                index += 2
            elif token.startswith("-"):
                following = argv[index + 1] if index + 1 < len(argv) else ""
                if following and not following.startswith("-"):
                    self.values[token] = following
                    index += 2
                else:
                    self.flags.add(token)
                    index += 1
            else:
                index += 1

    def inputs(self) -> list[str]:
        return self.values.get("--inputs", "").split(",")

    def outputs(self) -> list[str]:
        return self.values.get("--outputs", "").split(",")


class VerifierTestCase(unittest.TestCase):
    """Base fixture: a temporary git checkout with stub tools on PATH."""

    maxDiff = None

    def setUp(self) -> None:
        if shutil.which("git") is None:
            self.skipTest("git is required for the verifier fixture")
        if shutil.which("bash") is None:
            self.skipTest("bash is required for the stub compiler")
        tmp = Path(tempfile.mkdtemp(prefix="gala-verify-test-"))
        self.addCleanup(shutil.rmtree, tmp, True)
        self.repo = tmp / "repo"
        self.bin = tmp / "bin"
        self.home = tmp / "home"
        self.call_log = tmp / "calls.log"
        (self.repo / "server").mkdir(parents=True)
        self.bin.mkdir()
        (self.home / ".gala" / "stdlib" / "v9.9.9").mkdir(parents=True)

        subprocess.run(["git", "init", "-q", str(self.repo)], check=True)
        (self.repo / "flake.lock").write_text(
            json.dumps({"nodes": {"gala": {"locked": {"rev": "deadbeef"}}}}),
            encoding="utf-8",
        )
        (self.repo / "server" / "GALA_COMPILER").write_text(
            "compiler: GALA version 9.9.9\n"
            "flake_rev: deadbeef\n"
            "extraction: 9.9.9 cafe\n"
            "date: 2026-10-27\n",
            encoding="utf-8",
        )
        (self.home / ".gala" / "stdlib" / "v9.9.9" / ".stdlib-extracted").write_text(
            "9.9.9 cafe\n", encoding="utf-8"
        )
        for name, body in (
            ("gala", GALA_STUB),
            ("go", GO_STUB),
            ("gofmt", GOFMT_STUB),
        ):
            path = self.bin / name
            path.write_text(body, encoding="utf-8")
            path.chmod(0o755)

    # -- fixture helpers -------------------------------------------------

    def add_twin(self, rel: str, *lines: str) -> None:
        """Add a `.gala` source and the committed generated `.go` twin."""
        source = self.repo / "server" / f"{rel}.gala"
        source.parent.mkdir(parents=True, exist_ok=True)
        source.write_text("\n".join(lines) + "\n", encoding="utf-8")
        self.regenerate_committed(rel)

    def add_source_only(self, rel: str, *lines: str) -> None:
        source = self.repo / "server" / f"{rel}.gala"
        source.parent.mkdir(parents=True, exist_ok=True)
        source.write_text("\n".join(lines) + "\n", encoding="utf-8")

    def regenerate_committed(self, rel: str) -> None:
        source = self.repo / "server" / f"{rel}.gala"
        twin = self.repo / "server" / f"{rel}.go"
        twin.write_text(
            GENERATED_HEADER + "\n" + source.read_text(encoding="utf-8"),
            encoding="utf-8",
        )

    def modify_source(self, rel: str, line: str) -> None:
        source = self.repo / "server" / f"{rel}.gala"
        source.write_text(
            source.read_text(encoding="utf-8") + line + "\n", encoding="utf-8"
        )

    def run_verify(self, *args: str) -> subprocess.CompletedProcess[str]:
        if self.call_log.exists():
            self.call_log.unlink()
        env = os.environ.copy()
        env.pop("GALA_HOME", None)
        env.pop("NO_COLOR", None)
        env["HOME"] = str(self.home)
        env["PATH"] = f"{self.bin}{os.pathsep}{env.get('PATH', '')}"
        env["STUB_CALL_LOG"] = str(self.call_log)
        return subprocess.run(
            [sys.executable, str(VERIFY), *args],
            cwd=self.repo,
            env=env,
            capture_output=True,
            text=True,
            check=False,
        )

    def invocations(self, tool: str) -> list[Invocation]:
        if not self.call_log.exists():
            return []
        invocations = []
        for line in self.call_log.read_text(encoding="utf-8").splitlines():
            name, cwd, argv = line.split("\t", 2)
            if name != tool:
                continue
            invocations.append(Invocation(Path(cwd), argv.split()))
        return invocations

    def shared_calls(self) -> list[Invocation]:
        return [
            call
            for call in self.invocations("gala")
            if call.argv[:1] == ["transpile-package"]
        ]

    def single_calls(self) -> list[Invocation]:
        return [
            call for call in self.invocations("gala") if call.argv[:1] == ["transpile"]
        ]

    def output(self, result: subprocess.CompletedProcess[str]) -> str:
        return result.stdout + result.stderr

    def assert_ok(self, result: subprocess.CompletedProcess[str]) -> None:
        self.assertEqual(result.returncode, 0, self.output(result))

    # -- shared invocation ----------------------------------------------

    def test_clean_pass_uses_one_shared_invocation_per_package(self) -> None:
        for name in ("alpha", "beta", "gamma"):
            self.add_twin(f"models/{name}", "package models", f'val {name} = "{name}"')
        for name in ("one", "two"):
            self.add_twin(f"utils/{name}", "package utils", f'val {name} = "{name}"')

        result = self.run_verify()
        output = self.output(result)
        self.assert_ok(result)
        self.assertIn("found 5 .gala sources under server/", output)
        for rel in (
            "models/alpha.gala",
            "models/beta.gala",
            "models/gamma.gala",
            "utils/one.gala",
            "utils/two.gala",
        ):
            self.assertIn(f"] {rel} ... ok", output)
        self.assertIn("twins: 5 discovered, 5 transpiled, 5 ok", output)
        self.assertIn("verify.sh: OK (5 twins)", output)

        shared = self.shared_calls()
        self.assertEqual(len(shared), 2, "one shared invocation per package")
        self.assertEqual(self.single_calls(), [], "no per-twin transpile on a clean pass")

        by_dir = {
            call.cwd.relative_to(self.repo).as_posix(): call for call in shared
        }
        self.assertEqual(set(by_dir), {"server/models", "server/utils"})
        models = by_dir["server/models"]
        self.assertIn("--scan", models.flags)
        self.assertEqual(models.values["--stdlib-module"], "go.gala.fyi/stdlib")
        self.assertEqual(
            sorted(models.inputs()), ["alpha.gala", "beta.gala", "gamma.gala"]
        )
        self.assertEqual(len(models.outputs()), 3)
        self.assertEqual(len(set(models.outputs())), 3)
        self.assertEqual(sorted(by_dir["server/utils"].inputs()), ["one.gala", "two.gala"])

        gofmt = self.invocations("gofmt")
        self.assertEqual(len(gofmt), 1, "one gofmt invocation covers every twin")
        listed = [Path(arg) for arg in gofmt[0].argv if arg.endswith(".go")]
        self.assertEqual(len(listed), 5)

        log_path = self.repo / "server" / ".gala" / "verify.log"
        self.assertTrue(log_path.is_file(), "default run log is written")
        stamps = [
            line
            for line in log_path.read_text(encoding="utf-8").splitlines()
            if line
        ]
        self.assertTrue(stamps)
        for line in stamps:
            self.assertRegex(line, r"^\d\d:\d\d:\d\d ")

    # -- drift ----------------------------------------------------------

    def test_drift_is_per_twin_and_write_regenerates_it(self) -> None:
        self.add_twin("models/alpha", "package models", "val alpha = 1")
        self.add_twin("models/beta", "package models", "val beta = 1")
        self.modify_source("models/beta", "val added = 2")

        check = self.run_verify()
        output = self.output(check)
        self.assertEqual(check.returncode, 1, output)
        self.assertIn("models/alpha.gala ... ok", output)
        self.assertIn("models/beta.gala ... DRIFT", output)
        self.assertIn(
            "DRIFT: models/beta.gala does not regenerate byte-identically", output
        )
        self.assertIn("twins: 2 discovered, 2 transpiled, 1 ok, 1 drift", output)
        self.assertIn("verify.sh: FAILED", output)
        committed = (self.repo / "server" / "models" / "beta.go").read_text(
            encoding="utf-8"
        )
        self.assertNotIn("val added = 2", committed, "check mode must not write")

        written = self.run_verify("--write")
        output = self.output(written)
        self.assert_ok(written)
        self.assertIn("models/alpha.gala ... ok", output)
        self.assertIn("models/beta.gala ... wrote", output)
        self.assertIn("2 discovered, 2 transpiled, 1 unchanged, 1 regenerated", output)
        committed = (self.repo / "server" / "models" / "beta.go").read_text(
            encoding="utf-8"
        )
        self.assertIn("val added = 2", committed)

    def test_missing_committed_twin_is_reported(self) -> None:
        self.add_twin("models/alpha", "package models", "val alpha = 1")
        self.add_twin("models/beta", "package models", "val beta = 1")
        (self.repo / "server" / "models" / "beta.go").unlink()

        result = self.run_verify()
        output = self.output(result)
        self.assertEqual(result.returncode, 1, output)
        self.assertIn("models/alpha.gala ... ok", output)
        self.assertIn("models/beta.gala ... MISSING", output)
        self.assertIn("MISSING: models/beta.gala has no committed twin", output)
        self.assertIn("verify.sh: FAILED", output)

    def test_banned_runtime_import_is_reported_per_twin(self) -> None:
        self.add_twin("models/plain", "package models", "val plain = 1")
        self.add_twin(
            "models/runtime",
            "package models",
            'import "martianoff/gala/std"',
        )

        result = self.run_verify()
        output = self.output(result)
        self.assertEqual(result.returncode, 1, output)
        self.assertIn("models/plain.gala ... ok", output)
        self.assertIn("models/runtime.gala ... RUNTIME", output)
        self.assertIn(
            "RUNTIME: models/runtime.gala generates Go that imports the banned", output
        )

    # -- per-twin failure attribution ------------------------------------

    def test_transpile_failure_keeps_its_path_and_diagnostic(self) -> None:
        self.add_twin("models/good_one", "package models", "val goodOne = 1")
        self.add_twin("models/broken", "package models", "val broken = 1", "BROKEN")
        self.add_twin("models/good_two", "package models", "val goodTwo = 2")
        self.add_twin("utils/only", "package utils", "val only = 1")

        result = self.run_verify()
        output = self.output(result)
        self.assertEqual(result.returncode, 1, output)
        self.assertIn("models/good_one.gala ... ok", output)
        self.assertIn("models/broken.gala ... TRANSPILE", output)
        self.assertIn("models/good_two.gala ... ok", output)
        self.assertIn("utils/only.gala ... ok", output)
        self.assertIn("TRANSPILE: models/broken.gala does not transpile", output)
        self.assertIn("GALA-E9999: boom", output)
        self.assertIn("twins: 4 discovered, 3 transpiled, 3 ok, 1 transpile failure", output)
        self.assertIn("verify.sh: FAILED", output)

        shared = self.shared_calls()
        self.assertEqual(len(shared), 2, "both packages still get their shared call")
        models = next(
            call
            for call in shared
            if call.cwd == self.repo / "server" / "models"
        )
        self.assertEqual(
            sorted(models.inputs()), ["broken.gala", "good_one.gala", "good_two.gala"]
        )
        single = self.single_calls()
        self.assertEqual(len(single), 1, "the failed twin alone is retried")
        self.assertEqual(single[0].cwd, self.repo / "server" / "models")
        self.assertEqual(single[0].values["-i"], "broken.gala")

    # -- command-line and log contract -----------------------------------

    def test_cli_and_log_contract(self) -> None:
        self.add_twin("models/alpha", "package models", "val alpha = 1")

        verbose = self.run_verify("--verbose")
        output = self.output(verbose)
        self.assert_ok(verbose)
        self.assertIn("$ gala transpile-package", output)
        self.assertIn("--scan", output)
        self.assertIn("--stdlib-module go.gala.fyi/stdlib", output)

        (self.repo / "server" / ".gala" / "verify.log").unlink()
        no_log = self.run_verify("--no-log")
        self.assert_ok(no_log)
        self.assertIn("log:  (disabled)", self.output(no_log))
        self.assertFalse(
            (self.repo / "server" / ".gala" / "verify.log").exists(),
            "--no-log must not write the default run log",
        )

        custom_log = self.run_verify("--log", str(self.repo / "custom.log"))
        self.assert_ok(custom_log)
        self.assertIn(f"log:  {self.repo / 'custom.log'}", self.output(custom_log))
        self.assertTrue((self.repo / "custom.log").is_file())

        conflict = self.run_verify("--write", "--check")
        self.assertEqual(conflict.returncode, 2, self.output(conflict))
        conflict = self.run_verify(
            "--log", str(self.repo / "x.log"), "--no-log"
        )
        self.assertEqual(conflict.returncode, 2, self.output(conflict))


if __name__ == "__main__":
    unittest.main(verbosity=2)
