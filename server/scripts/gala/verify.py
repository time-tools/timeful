#!/usr/bin/env python3
"""Verify the committed GALA twins in server/.

Usage:
    server/scripts/gala/verify.sh          # drift detection
    server/scripts/gala/verify.sh --write  # regenerate the committed twins in place

The verifier prints the compiler provenance recorded in server/GALA_COMPILER,
transpiles every committed twin with the adopted --stdlib-module, then fails on
a missing or mismatched provenance record, on a twin the compiler does not
regenerate byte-identically, on a twin whose generated Go imports the banned
martianoff/gala runtime, on a `gofmt -l` hit, on an orphaned generated twin, or
on a failing `go build ./...`.

The transpiles run through `gala transpile-package`, one shared invocation per
source directory, so the compiler builds a package's Go type information once
instead of once per twin.  Every twin is still checked independently; a twin
whose output is absent from a failed shared invocation is retried on its own
with `gala transpile`, keeping its path and compiler diagnostic while the rest
of the package and the remaining packages are still verified.

Progress is printed per twin and per phase.  Every run also writes a
timestamped log to server/.gala/verify.log; --log FILE moves it and --no-log
disables it.  --verbose adds each shared compiler command and the compiler
output of a package or a retried twin.

The regression check is `python3 server/scripts/gala/test_verify.py`; it stubs
`gala` in a temporary fixture and does not need the real compiler.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import shlex
import shutil
import subprocess
import sys
import tempfile
import time
from collections.abc import Iterator, Sequence
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path

GENERATED_HEADER = "// Code generated by GALA transpiler. DO NOT EDIT."
STDLIB_MODULE = "go.gala.fyi/stdlib"
BANNED_RUNTIME_RE = re.compile(r'"martianoff/gala')
PROBE_PARTS = ("scripts", "gala", "probes")
HEARTBEAT_SECONDS = 15
DIAGNOSTIC_LINE_LIMIT = 20

ANSI = {
    "bold": "\033[1m",
    "dim": "\033[2m",
    "red": "\033[31m",
    "green": "\033[32m",
    "yellow": "\033[33m",
    "cyan": "\033[36m",
}


def gala_state_dir() -> Path:
    """Return the compiler's state root, honouring a relocated ``GALA_HOME``.

    ``.envrc`` points ``GALA_HOME`` at ``.local/gala`` so the compiler keeps its
    stdlib extraction inside the checkout, and the verifier has to read the
    marker the compiler is actually using rather than assuming ``~/.gala``.
    """
    home = os.environ.get("GALA_HOME")
    if home:
        return Path(os.path.expanduser(home))
    return Path.home() / ".gala"


class Fatal(Exception):
    """An environment problem that stops the run before any checking happens."""


def repo_root() -> Path:
    try:
        completed = subprocess.run(
            ["git", "rev-parse", "--show-toplevel"],
            capture_output=True,
            text=True,
            check=False,
        )
    except OSError as exc:
        raise Fatal(f"cannot run git: {exc}") from exc
    if completed.returncode != 0:
        raise Fatal("not inside a git work tree")
    return Path(completed.stdout.strip())


def last_line(text: str) -> str:
    lines = text.rstrip("\n").splitlines()
    return lines[-1] if lines else ""


def fmt_duration(seconds: float) -> str:
    if seconds < 60:
        return f"{seconds:.1f}s"
    minutes, remainder = divmod(round(seconds), 60)
    return f"{minutes}m{remainder:02d}s"


def plural(count: int, singular: str, plural_form: str | None = None) -> str:
    if count == 1:
        return f"{count} {singular}"
    return f"{count} {plural_form or singular + 's'}"


def format_command(argv: Sequence[str]) -> str:
    return shlex.join(argv)


def iter_tree_files(root: Path, pattern: str) -> Iterator[Path]:
    """Yield repo-relative files matching pattern, skipping the cache and probes."""
    for path in root.rglob(pattern):
        if not path.is_file():
            continue
        rel = path.relative_to(root)
        if rel.parts and rel.parts[0] == ".gala":
            continue
        if rel.parts[: len(PROBE_PARTS)] == PROBE_PARTS:
            continue
        yield rel


def first_line(path: Path) -> str:
    try:
        with path.open("r", encoding="utf-8", errors="replace") as handle:
            return handle.readline().rstrip("\n")
    except OSError:
        return ""


def group_sources(sources: Sequence[Path]) -> list[list[Path]]:
    """Group sorted twins into the source directories the compiler batches.

    The sources are sorted by path, so a directory's twins are contiguous.  A
    shared `gala transpile-package` call covers one directory; every directory
    holds one GALA package in this repository, and the compiler resolves the
    package's siblings from the directory itself (`--scan`), so a directory
    whose files belong to two packages is still handled correctly.
    """
    groups: list[list[Path]] = []
    for rel in sources:
        if groups and groups[-1][0].parent == rel.parent:
            groups[-1].append(rel)
        else:
            groups.append([rel])
    return groups


@dataclass
class PackageBatch:
    """The result of one shared `gala transpile-package` invocation."""

    code: int
    output: str
    outputs: dict[Path, Path]

    def output_for(self, rel: Path) -> Path:
        """Return the scratch output path reserved for one twin."""
        return self.outputs[rel]


def parse_provenance(text: str) -> dict[str, str]:
    values = {"compiler": "", "flake_rev": "", "extraction": "", "date": ""}
    for line in text.splitlines():
        for key in values:
            prefix = f"{key}: "
            if line.startswith(prefix):
                values[key] = line[len(prefix) :]
    return values


class Reporter:
    """Print progress to the terminal and duplicate every line to the run log."""

    def __init__(self, log_path: Path | None) -> None:
        self.color = sys.stdout.isatty() and not os.environ.get("NO_COLOR")
        self.log_path = None
        self._stream = None
        if log_path is None:
            return
        try:
            log_path.parent.mkdir(parents=True, exist_ok=True)
            self._stream = log_path.open("w", encoding="utf-8", errors="replace")
        except OSError as exc:
            print(
                f"verify.sh: cannot write log file {log_path}: {exc}",
                file=sys.stderr,
            )
            return
        self.log_path = log_path

    def _paint(self, text: str, style: str | None) -> str:
        if not self.color or not style:
            return text
        return f"{ANSI[style]}{text}\033[0m"

    def _record(self, text: str) -> None:
        if self._stream is None:
            return
        stamp = datetime.now().strftime("%H:%M:%S")
        for line in text.splitlines() or [""]:
            self._stream.write(f"{stamp} {line}\n")
        self._stream.flush()

    def line(self, text: str = "", *, style: str | None = None, log: bool = True) -> None:
        print(self._paint(text, style), flush=True)
        if log:
            self._record(text)

    def block(self, text: str, *, style: str | None = None) -> None:
        body = text.rstrip("\n")
        if not body:
            return
        for line in body.splitlines():
            print(self._paint(line, style), flush=True)
        self._record(body)

    def record(self, text: str) -> None:
        self._record(text)

    def header(self, title: str) -> None:
        self.line()
        self.line(f"== {title} ==", style="bold")

    def progress_start(self, text: str) -> None:
        """Show the twin being checked before the slow step finishes."""
        sys.stdout.write(text)
        sys.stdout.flush()

    def progress_end(self, prefix: str, status: str, *, style: str | None = None) -> None:
        sys.stdout.write(self._paint(status, style) + "\n")
        sys.stdout.flush()
        self._record(prefix + status)

    def close(self) -> None:
        if self._stream is not None:
            self._stream.close()
            self._stream = None


def run_captured(
    reporter: Reporter,
    argv: Sequence[str],
    cwd: Path,
    *,
    label: str | None = None,
    heartbeat: int = HEARTBEAT_SECONDS,
) -> tuple[int, str]:
    """Run argv with combined output captured, emitting heartbeats while slow."""
    started = time.monotonic()
    try:
        sink = tempfile.TemporaryFile(mode="w+", encoding="utf-8", errors="replace")
    except OSError as exc:
        return 127, f"cannot create a scratch file: {exc}\n"
    try:
        try:
            process = subprocess.Popen(
                list(argv),
                cwd=str(cwd),
                stdout=sink,
                stderr=subprocess.STDOUT,
                text=True,
            )
        except OSError as exc:
            return 127, f"{argv[0]}: {exc}\n"
        while True:
            if label is None:
                process.wait()
                break
            try:
                process.wait(timeout=heartbeat)
                break
            except subprocess.TimeoutExpired:
                reporter.line(
                    f"    ... {label} still running"
                    f" ({fmt_duration(time.monotonic() - started)})",
                    style="dim",
                )
        sink.seek(0)
        return process.returncode, sink.read()
    finally:
        sink.close()


def report_output(reporter: Reporter, output: str) -> None:
    """Show captured diagnostics, keeping the full text in the log."""
    lines = output.rstrip("\n").splitlines()
    reporter.record("\n".join(lines))
    if not lines:
        reporter.line("    (no output)", style="dim", log=False)
        return
    for line in lines[:DIAGNOSTIC_LINE_LIMIT]:
        reporter.line(f"    {line}", style="dim", log=False)
    remaining = len(lines) - DIAGNOSTIC_LINE_LIMIT
    if remaining > 0:
        hint = f"; full output in {reporter.log_path}" if reporter.log_path else ""
        reporter.line(f"    ... ({remaining} more lines{hint})", style="dim", log=False)


class Verifier:
    def __init__(
        self,
        args: argparse.Namespace,
        reporter: Reporter,
        root: Path,
        scratch_dir: Path,
    ) -> None:
        self.args = args
        self.reporter = reporter
        self.root = root
        self.server_dir = root / "server"
        self.provenance_file = self.server_dir / "GALA_COMPILER"
        self.scratch_dir = scratch_dir
        self.mode = "write" if args.write else "check"
        self.status = 0
        self.problems: list[str] = []
        self.gofmt_targets: list[Path] = []
        self.twin_count = 0
        self.discovered = 0
        self.counts = {
            "ok": 0,
            "drift": 0,
            "runtime": 0,
            "missing": 0,
            "transpile": 0,
            "wrote": 0,
            "unchanged": 0,
        }

    def run(self) -> int:
        reporter = self.reporter
        reporter.line(f"verify.sh: GALA twin verifier ({self.mode} mode)", style="bold")
        reporter.line(f"repo: {self.root}")
        reporter.line(
            f"log:  {reporter.log_path if reporter.log_path else '(disabled)'}"
        )
        started = time.monotonic()
        self.check_provenance()
        self.check_twins()
        self.check_gofmt()
        self.check_orphans()
        self.check_build()
        self.summarize(time.monotonic() - started)
        return self.status

    def problem(self, label: str, message: str, *, indent: int = 0) -> None:
        self.status = 1
        text = f"{label}: {message}"
        self.problems.append(text)
        self.reporter.line(" " * indent + text, style="red")

    def check_provenance(self) -> None:
        reporter = self.reporter
        reporter.header("provenance")
        started = time.monotonic()
        problems_before = len(self.problems)

        gala_path = shutil.which("gala")
        if gala_path is None:
            raise Fatal("`gala` is not on PATH; run inside `nix develop`")
        code, output = run_captured(reporter, ["gala", "version"], self.root)
        if code != 0:
            raise Fatal(f"`gala version` exited {code}:\n{output.rstrip()}")
        current_compiler = last_line(output)
        locked_rev = self.read_locked_rev()
        go_version = self.read_go_version()

        reporter.line(f"gala version: {current_compiler}")
        reporter.line(f"which gala:   {gala_path}")
        reporter.line(f"go:           {go_version}")
        reporter.line(f"flake rev:    {locked_rev}")

        recorded: dict[str, str] | None = None
        if not self.provenance_file.is_file():
            reporter.line(f"recorded provenance: MISSING ({self.provenance_file})")
            self.problem(
                "PROVENANCE",
                f"{self.provenance_file} is missing; run a bump iteration and record it",
            )
        else:
            text = self.provenance_file.read_text(encoding="utf-8", errors="replace")
            recorded = parse_provenance(text)
            reporter.line("recorded provenance:")
            for line in text.splitlines():
                reporter.line(f"  {line}")
            if recorded["compiler"] != current_compiler:
                self.problem(
                    "PROVENANCE",
                    f"{self.provenance_file} records compiler"
                    f" '{recorded['compiler']}' but gala reports"
                    f" '{current_compiler}'; run a bump iteration",
                )
            if recorded["flake_rev"] and recorded["flake_rev"] != locked_rev:
                self.problem(
                    "PROVENANCE",
                    f"{self.provenance_file} records {recorded['flake_rev']} but"
                    f" flake.lock locks {locked_rev}; run a bump iteration",
                )
            self.check_extraction(recorded)

        duration = fmt_duration(time.monotonic() - started)
        if len(self.problems) == problems_before:
            reporter.line(f"provenance: ok ({duration})", style="green")
        else:
            reporter.line(f"provenance: failed ({duration})", style="red")

    def check_extraction(self, recorded: dict[str, str]) -> None:
        extraction = recorded["extraction"]
        if not extraction:
            self.problem(
                "PROVENANCE",
                f"{self.provenance_file} records no extraction fingerprint;"
                " run a bump iteration and record it",
            )
            return
        version = extraction.split(" ", 1)[0]
        marker = gala_state_dir() / "stdlib" / f"v{version}" / ".stdlib-extracted"
        current = ""
        if marker.is_file():
            current = marker.read_text(encoding="utf-8", errors="replace").rstrip("\n")
        if current != extraction:
            self.problem(
                "PROVENANCE",
                f"{self.provenance_file} records extraction '{extraction}' but"
                f" {marker} is '{current}'; run a bump iteration",
            )

    def read_locked_rev(self) -> str:
        path = self.root / "flake.lock"
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
            rev = data["nodes"]["gala"]["locked"]["rev"]
        except (OSError, ValueError, KeyError, TypeError) as exc:
            raise Fatal(f"cannot read the gala rev from {path}: {exc}") from exc
        if not isinstance(rev, str) or not rev:
            raise Fatal(f"{path} has no string nodes.gala.locked.rev")
        return rev

    def read_go_version(self) -> str:
        code, output = run_captured(self.reporter, ["go", "version"], self.root)
        return last_line(output) if code == 0 else "(unavailable)"

    def check_twins(self) -> None:
        reporter = self.reporter
        title = "twins (--write)" if self.args.write else "twins (drift detection)"
        reporter.header(title)
        started = time.monotonic()
        problems_before = len(self.problems)

        sources = sorted(iter_tree_files(self.server_dir, "*.gala"), key=str)
        self.discovered = len(sources)
        reporter.line(f"found {plural(len(sources), '.gala source')} under server/")
        width = len(str(len(sources))) if sources else 1
        total = len(sources)
        positions = {rel: index for index, rel in enumerate(sources, 1)}
        for group in group_sources(sources):
            self.check_package(group, positions, total, width)

        parts = [
            f"{self.discovered} discovered",
            f"{self.twin_count} transpiled",
        ]
        if self.args.write:
            parts.append(f"{self.counts['unchanged']} unchanged")
            if self.counts["wrote"]:
                parts.append(f"{self.counts['wrote']} regenerated")
        else:
            parts.append(f"{self.counts['ok']} ok")
        for key in ("drift", "runtime", "missing"):
            if self.counts[key]:
                parts.append(plural(self.counts[key], key))
        if self.counts["transpile"]:
            parts.append(
                plural(self.counts["transpile"], "transpile failure", "transpile failures")
            )
        duration = fmt_duration(time.monotonic() - started)
        ok = len(self.problems) == problems_before
        reporter.line(
            f"twins: {', '.join(parts)} ({duration})",
            style="green" if ok else "red",
        )

    def twin_prefix(self, index: int, total: int, width: int, rel: Path) -> str:
        percent = int(index * 100 / total) if total else 100
        return f"[{index:>{width}}/{total} {percent:>3}%] {rel.as_posix()} ... "

    def scratch_path(self, rel: Path) -> Path:
        """Return the scratch file reserved for one twin's regenerated output."""
        name = rel.as_posix().replace("/", "_").replace(".", "_") + ".go"
        return self.scratch_dir / name

    def package_command(
        self, rels: Sequence[Path], outputs: dict[Path, Path]
    ) -> list[str]:
        """Build the shared transpile-package command for one directory."""
        return [
            "gala",
            "transpile-package",
            "--scan",
            "--stdlib-module",
            STDLIB_MODULE,
            "--inputs",
            ",".join(rel.name for rel in rels),
            "--outputs",
            ",".join(str(outputs[rel]) for rel in rels),
        ]

    def twin_command(self, rel: Path, scratch: Path) -> list[str]:
        """Build the single-file fallback command for one twin."""
        return [
            "gala",
            "transpile",
            "--stdlib-module",
            STDLIB_MODULE,
            "-i",
            rel.name,
            "-o",
            str(scratch),
        ]

    def check_package(
        self,
        rels: Sequence[Path],
        positions: dict[Path, int],
        total: int,
        width: int,
    ) -> None:
        """Verify one source directory through one shared compiler invocation."""
        reporter = self.reporter
        needs_compiler = any(
            (self.server_dir / rel.with_suffix(".go")).is_file() for rel in rels
        )
        first_prefix = self.twin_prefix(positions[rels[0]], total, width, rels[0])
        batch: PackageBatch | None = None
        if needs_compiler:
            outputs = {rel: self.scratch_path(rel) for rel in rels}
            argv = self.package_command(rels, outputs)
            if self.args.verbose:
                reporter.line(f"    $ {format_command(argv)}", style="dim")
            reporter.progress_start(first_prefix)
            code, output = run_captured(
                reporter, argv, self.server_dir / rels[0].parent
            )
            batch = PackageBatch(code=code, output=output, outputs=outputs)
            if code != 0 and not self.args.verbose:
                reporter.record(output)

        for index, rel in enumerate(rels):
            if index == 0 and batch is not None:
                prefix = first_prefix
            else:
                prefix = self.twin_prefix(positions[rel], total, width, rel)
                reporter.progress_start(prefix)
            self.check_twin(rel, prefix, batch)

        if self.args.verbose and batch is not None and batch.output.strip():
            reporter.block(batch.output.rstrip("\n"), style="dim")

    def check_twin(self, rel: Path, prefix: str, batch: PackageBatch | None) -> None:
        reporter = self.reporter
        rel_text = rel.as_posix()

        twin_rel = rel.with_suffix(".go")
        twin = self.server_dir / twin_rel
        twin_text = twin_rel.as_posix()
        if not twin.is_file():
            reporter.progress_end(prefix, "MISSING", style="red")
            self.problem(
                "MISSING",
                f"{rel_text} has no committed twin at {twin_text}",
                indent=4,
            )
            self.counts["missing"] += 1
            return

        scratch = (
            batch.output_for(rel) if batch is not None else self.scratch_path(rel)
        )
        retried = False
        argv: list[str] = []
        output = ""
        if batch is not None and scratch.is_file():
            code = 0
        else:
            retried = True
            argv = self.twin_command(rel, scratch)
            code, output = run_captured(
                reporter, argv, self.server_dir / rel.parent
            )
        if code != 0 or not scratch.is_file():
            reporter.progress_end(prefix, "TRANSPILE", style="red")
            if retried and self.args.verbose:
                reporter.line(f"    $ {format_command(argv)}", style="dim")
            self.problem(
                "TRANSPILE",
                f"{rel_text} does not transpile",
                indent=4,
            )
            report_output(reporter, output)
            self.counts["transpile"] += 1
            return

        self.twin_count += 1
        self.gofmt_targets.append(twin)

        issues: list[tuple[str, str]] = []
        try:
            generated = scratch.read_text(encoding="utf-8", errors="replace")
        except OSError:
            generated = ""
        if BANNED_RUNTIME_RE.search(generated):
            issues.append(
                (
                    "RUNTIME",
                    f"{rel_text} generates Go that imports the banned"
                    " martianoff/gala runtime; only"
                    f" {STDLIB_MODULE} imports are allowed",
                )
            )

        wrote = False
        if self.args.write:
            if twin.read_bytes() != scratch.read_bytes():
                shutil.copyfile(scratch, twin)
                wrote = True
                self.counts["wrote"] += 1
            else:
                self.counts["unchanged"] += 1
        elif twin.read_bytes() != scratch.read_bytes():
            issues.append(
                ("DRIFT", f"{rel_text} does not regenerate byte-identically")
            )

        if issues:
            labels = [label for label, _ in issues]
            reporter.progress_end(prefix, ", ".join(labels), style="yellow")
            for label, message in issues:
                self.problem(label, message, indent=4)
                self.counts[label.lower()] += 1
        elif self.args.write:
            reporter.progress_end(prefix, "wrote" if wrote else "ok", style="green")
        else:
            reporter.progress_end(prefix, "ok", style="green")
            self.counts["ok"] += 1

        if retried and self.args.verbose:
            reporter.line(f"    $ {format_command(argv)}", style="dim")
            if output.strip():
                reporter.block(output.rstrip("\n"), style="dim")

    def check_gofmt(self) -> None:
        reporter = self.reporter
        reporter.header("gofmt")
        started = time.monotonic()
        problems_before = len(self.problems)
        if not self.gofmt_targets:
            reporter.line("gofmt: no generated twins to check (0.0s)")
            return
        argv = ["gofmt", "-l", *[str(path) for path in self.gofmt_targets]]
        if self.args.verbose:
            reporter.line(
                f"    $ gofmt -l ({plural(len(self.gofmt_targets), 'path')})",
                style="dim",
            )
        code, output = run_captured(reporter, argv, self.root)
        if code != 0:
            self.problem("GOFMT", f"gofmt -l exited {code}")
            report_output(reporter, output)
        elif output.strip():
            self.status = 1
            reporter.line("GOFMT:", style="red")
            reporter.block(output.rstrip("\n"))
            self.problems.append("GOFMT: generated twins are not gofmt-clean")

        duration = fmt_duration(time.monotonic() - started)
        ok = len(self.problems) == problems_before
        reporter.line(
            f"gofmt: {len(self.gofmt_targets)} checked,"
            f" {'ok' if ok else 'failed'} ({duration})",
            style="green" if ok else "red",
        )

    def check_orphans(self) -> None:
        reporter = self.reporter
        reporter.header("orphan scan")
        started = time.monotonic()
        problems_before = len(self.problems)
        generated = sorted(iter_tree_files(self.server_dir, "*.go"), key=str)
        for rel in generated:
            if first_line(self.server_dir / rel) != GENERATED_HEADER:
                continue
            source_rel = rel.with_suffix(".gala")
            if not (self.server_dir / source_rel).is_file():
                self.problem(
                    "ORPHAN",
                    f"{rel.as_posix()} carries the generated header but"
                    f" {source_rel.as_posix()} is missing",
                )
        duration = fmt_duration(time.monotonic() - started)
        ok = len(self.problems) == problems_before
        reporter.line(
            f"orphan scan: {plural(len(generated), 'Go file')},"
            f" {'ok' if ok else 'failed'} ({duration})",
            style="green" if ok else "red",
        )

    def check_build(self) -> None:
        reporter = self.reporter
        reporter.header("go build ./...")
        started = time.monotonic()
        problems_before = len(self.problems)
        if self.args.verbose:
            reporter.line("    $ go build ./...", style="dim")
        code, output = run_captured(
            reporter,
            ["go", "build", "./..."],
            self.server_dir,
            label="go build ./...",
        )
        if code != 0:
            self.problem("BUILD", "go build ./... failed")
            reporter.block(output.rstrip("\n"))
        elif self.args.verbose and output.strip():
            reporter.block(output.rstrip("\n"), style="dim")
        duration = fmt_duration(time.monotonic() - started)
        ok = len(self.problems) == problems_before
        reporter.line(
            f"go build: {'ok' if ok else 'failed'} ({duration})",
            style="green" if ok else "red",
        )

    def summarize(self, duration: float) -> None:
        reporter = self.reporter
        reporter.header("summary")
        reporter.line(f"total:   {fmt_duration(duration)}")
        if self.problems:
            reporter.line(f"problems: {len(self.problems)}", style="red")
            for text in self.problems:
                reporter.line(f"  {text}", style="red")
        reporter.line(f"log:     {reporter.log_path or '(disabled)'}")
        if self.status == 0:
            reporter.line(f"verify.sh: OK ({self.twin_count} twins)", style="green")
        else:
            reporter.line("verify.sh: FAILED", style="red")


def parse_args(argv: Sequence[str] | None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        prog="verify.sh",
        description=(
            "Verify the committed GALA twins in server/.  Each source"
            " directory's twins travel through one shared `gala"
            " transpile-package` invocation and are still checked"
            " independently."
        ),
        epilog=(
            "The run log defaults to server/.gala/verify.log; every line carries"
            " a timestamp.  Exit codes: 0 verified, 1 verification failed,"
            " 2 usage."
        ),
    )
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument(
        "--write",
        action="store_true",
        help="regenerate the committed twins in place",
    )
    mode.add_argument(
        "--check",
        action="store_true",
        help="detect drift without writing (default)",
    )
    parser.add_argument(
        "-v",
        "--verbose",
        action="store_true",
        help=(
            "show each shared compiler command and the compiler output of a"
            " package or a twin retried on its own"
        ),
    )
    logging_group = parser.add_mutually_exclusive_group()
    logging_group.add_argument(
        "--log",
        metavar="FILE",
        help="write the run log to FILE instead of server/.gala/verify.log",
    )
    logging_group.add_argument(
        "--no-log",
        action="store_true",
        help="do not write a run log",
    )
    return parser.parse_args(argv)


def main(argv: Sequence[str] | None = None) -> int:
    args = parse_args(argv)
    reporter: Reporter | None = None
    try:
        root = repo_root()
        if not (root / "server").is_dir():
            raise Fatal(f"{root}/server does not exist; run inside the timeful checkout")
        if args.no_log:
            log_path = None
        elif args.log:
            log_path = Path(args.log).expanduser()
        else:
            log_path = root / "server" / ".gala" / "verify.log"
        reporter = Reporter(log_path)
        with tempfile.TemporaryDirectory(prefix="gala-verify-") as scratch:
            return Verifier(args, reporter, root, Path(scratch)).run()
    except Fatal as exc:
        if reporter is not None:
            reporter.line(f"verify.sh: {exc}", style="red")
            reporter.line("verify.sh: FAILED", style="red")
        else:
            print(f"verify.sh: {exc}", file=sys.stderr)
        return 1
    except KeyboardInterrupt:
        if reporter is not None:
            reporter.line("verify.sh: interrupted", style="red")
        else:
            print("verify.sh: interrupted", file=sys.stderr)
        return 130
    finally:
        if reporter is not None:
            reporter.close()


if __name__ == "__main__":
    sys.exit(main())
